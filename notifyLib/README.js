/**
 * ============================================================
 * NotifyLib - 跨平台通知函式庫
 * ============================================================
 *
 * 📦 專案名稱:NotifyLib
 * 🆔 建議識別碼:Notify
 *
 * 📍 用途
 *   提供跨平台通知能力,業務層只依賴抽象介面,
 *   不關心實際發送平台(目前支援 Google Chat)。
 *
 * ────────────────────────────────────────────────────────────
 * 📚 模組列表
 * ────────────────────────────────────────────────────────────
 *   ► Notifier      - 抽象基底類別(定義介面)
 *   ► ChatNotifier  - Google Chat 實作
 *
 *   未來規劃(尚未實作):
 *   - SlackNotifier   - Slack 通知
 *   - TeamsNotifier   - Microsoft Teams 通知
 *   - EmailNotifier   - Email 通知
 *
 * ────────────────────────────────────────────────────────────
 * 🚀 引用方式
 * ────────────────────────────────────────────────────────────
 *
 * 1️⃣ 在其他 Apps Script 專案的「程式庫」加入:
 *    - Script ID:(從本專案「專案設定」取得)
 *    - 版本:選擇穩定版本
 *    - 識別碼:Notify
 *
 * 2️⃣ 取得實例:
 *    const notifier = Notify.createChatNotifier(webhookUrl);
 *
 * 3️⃣ 發送純文字:
 *    notifier.send('Hello from Apps Script');
 *
 * 4️⃣ 發送 Card(結構化訊息):
 *    notifier.sendCard({
 *      title: '✅ Sprint 0427-0508 已建立',
 *      subtitle: '請確認表單內容後發布',
 *      fields: [
 *        { label: '資料夾', value: '0427-0508', link: 'https://...' },
 *        { label: '表單', value: 'Sprint 回顧問卷', link: 'https://...' },
 *      ],
 *      actions: [
 *        { text: '開啟資料夾', url: 'https://...' },
 *      ],
 *    });
 *
 * ────────────────────────────────────────────────────────────
 * 💡 設計原則
 * ────────────────────────────────────────────────────────────
 *   ► 抽象基底類別(Notifier)定義共通介面
 *   ► 各平台 Notifier 繼承後實作 send / sendCard
 *   ► 業務層只依賴抽象,不知道實作細節(IOC)
 *   ► 統一 Message 結構,各平台內部轉換為自家格式
 *   ► 失敗印 log 不拋例外,通知失敗不阻斷主流程
 *
 * ────────────────────────────────────────────────────────────
 * 📋 統一 Message 結構
 * ────────────────────────────────────────────────────────────
 *   {
 *     title:    string,           // 標題(必填)
 *     subtitle: string,           // 副標題(可選)
 *     fields: [                   // 結構化欄位(可選)
 *       {
 *         label: string,
 *         value: string,
 *         link:  string(可選)    // 有連結時自動顯示「開啟」按鈕
 *       }
 *     ],
 *     actions: [                  // 底部按鈕(可選)
 *       { text: string, url: string }
 *     ],
 *   }
 *
 * ────────────────────────────────────────────────────────────
 * 📋 版本記錄
 * ────────────────────────────────────────────────────────────
 *   v1.0 (2026/05) - 初始版本
 *     ► Notifier 抽象基底
 *     ► ChatNotifier(Google Chat Webhook)
 *
 * ────────────────────────────────────────────────────────────
 * ⚠️ 使用注意事項
 * ────────────────────────────────────────────────────────────
 *   1. Webhook URL 請存於引用方專案的 Script Properties,
 *      不要寫死在程式碼中
 *   2. 通知失敗時只印 log 不拋例外,引用方需自行檢查回傳值
 *   3. 修改 Library 後需重新部署版本,引用方才會看到變更
 *
 * ============================================================
 */